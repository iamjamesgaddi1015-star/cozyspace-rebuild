import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { writeFile } from 'node:fs/promises';
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const checks=[];
const baseUrl=process.env.COZYSPACE_URL || 'http://127.0.0.1:5175/';
const record=(name,detail='passed')=>checks.push({name,detail});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const errors=[];
  const failures=[];
  const requests=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('response',response=>{if(response.status()>=400) failures.push({url:response.url(),status:response.status()});});
  page.on('request',request=>requests.push(request.url()));
  await page.goto(baseUrl,{waitUntil:'networkidle'});
  await page.evaluate(()=>document.fonts.ready);
  assert.match(await page.title(),/^CozySpace/);
  assert.equal(await page.locator('h1').count(),1);
  assert.equal(await page.locator('.scene').count(),7);
  record('CozySpace metadata, single main heading, seven service chapters');
  assert.equal(await page.evaluate(()=>document.fonts.check('500 16px Manrope')),true);
  assert.equal(await page.evaluate(()=>document.fonts.check('400 16px "Libre Caslon Display"')),true);
  record('Both original font families load locally');
  await page.screenshot({path:'inspection/local-desktop.png'});
  await page.getByRole('button',{name:'Show the wardrobe',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Show the wardrobe',exact:true}).getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('.hero-slide.is-active').getAttribute('src'),'/images/wardrobe.png');
  await page.getByRole('button',{name:'Show the kitchen',exact:true}).click();
  record('Room selector changes the image and pressed state');
  await page.getByRole('link',{name:'Explore',exact:true}).click();
  assert.equal(new URL(page.url()).hash,'#story');
  await page.locator('#spaces').scrollIntoViewIfNeeded();
  await page.screenshot({path:'inspection/local-services.png'});
  for(const chapter of await page.locator('.scene').all()) {
    await chapter.scrollIntoViewIfNeeded();
    await chapter.locator('img').evaluate(image=>image.decode());
  }
  const brokenImages=await page.locator('img').evaluateAll(images=>images.filter(i=>i.complete&&i.naturalWidth===0).map(i=>i.src));
  assert.deepEqual(brokenImages,[]);
  record('Every service photograph decodes successfully');
  const anchors=await page.locator('a[href^="#"]').evaluateAll(links=>links.map(link=>({href:link.getAttribute('href'),exists:!!document.getElementById(link.getAttribute('href').slice(1))})));
  assert.equal(anchors.every(a=>a.exists),true);
  record('All internal navigation destinations exist');
  await page.locator('#philosophy').scrollIntoViewIfNeeded();
  await page.screenshot({path:'inspection/local-approach.png'});
  const cta=page.getByRole('button',{name:'Start a conversation',exact:true});
  await cta.click();
  const dialog=page.getByRole('dialog');
  assert.equal(await dialog.isVisible(),true);
  assert.equal(await page.evaluate(()=>document.activeElement?.getAttribute('aria-label')),'Close contact options');
  assert.equal(await dialog.locator('a').count(),2);
  const urls=await dialog.locator('a').evaluateAll(links=>links.map(a=>a.href));
  assert.deepEqual(urls,['https://wa.me/message/U2FXIPFM2PVQL1','https://wa.me/message/JRT7BRKW4MI5J1']);
  await page.screenshot({path:'inspection/local-contact-dialog.png'});
  for(let i=0;i<6;i++) {
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(()=>!!document.activeElement?.closest('dialog')),true);
  }
  await page.keyboard.press('Escape');
  assert.equal(await dialog.isVisible(),false);
  assert.equal(await cta.evaluate(e=>document.activeElement===e),true);
  assert.equal(await page.evaluate(()=>document.body.classList.contains('dialog-open')),false);
  record('Contact dialog: destinations, initial focus, focus containment, Escape, focus restoration, scroll unlock');
  await cta.click();
  await page.mouse.click(5,5);
  assert.equal(await dialog.isVisible(),false);
  record('Backdrop click closes contact options');
  for(const width of [1440,1280,1024,800,768,390,320]) {
    await page.setViewportSize({width,height:900});
    await page.evaluate(()=>window.scrollTo(0,0));
    const overflow=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
    assert.ok(overflow.scroll<=overflow.client+1,`Horizontal overflow at ${width}: ${JSON.stringify(overflow)}`);
    if(width===390) await page.screenshot({path:'inspection/local-mobile.png'});
    if(width===320) await page.screenshot({path:'inspection/local-small-phone.png'});
  }
  record('No horizontal page overflow at 1440, 1280, 1024, 800, 768, 390 and 320px');
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.getByRole('button',{name:'Open menu',exact:true}).click();
  await page.screenshot({path:'inspection/local-mobile-menu.png'});
  assert.equal(await page.getByRole('button',{name:'Close menu'}).getAttribute('aria-expanded'),'true');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button',{name:'Open menu'}).evaluate(e=>document.activeElement===e),true);
  await page.getByRole('button',{name:'Open menu'}).click();
  await page.getByRole('navigation').getByRole('link',{name:'Our services',exact:true}).click();
  assert.equal(new URL(page.url()).hash,'#spaces');
  assert.equal(await page.getByRole('button',{name:'Open menu'}).getAttribute('aria-expanded'),'false');
  record('Mobile menu: open, Escape, focus restore, navigation and auto-close');
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.getByRole('button',{name:'Open menu'}).click();
  await page.getByRole('navigation').getByRole('button',{name:'Let’s talk'}).click();
  assert.equal(await dialog.isVisible(),true);
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button',{name:'Open menu'}).evaluate(e=>document.activeElement===e),true);
  record('Mobile menu contact action opens dialog');
  await page.setViewportSize({width:640,height:450});
  await page.goto(baseUrl,{waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Start a conversation',exact:true}).click();
  await dialog.getByRole('link').last().scrollIntoViewIfNeeded();
  assert.equal(await dialog.getByRole('link').last().isVisible(),true);
  await page.keyboard.press('Escape');
  record('Short viewport / 200% equivalent reflow: contact options remain reachable');
  assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).scrollBehavior),'auto');
  record('Reduced motion disables smooth scrolling');
  assert.equal(requests.every(url=>url.startsWith(baseUrl)),true);
  record('Rendered page makes no external network requests');
  await page.context().setOffline(true);
  await page.getByRole('button',{name:'Show the wardrobe',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Show the wardrobe',exact:true}).getAttribute('aria-pressed'),'true');
  record('Already-loaded page interaction works offline; no form falsely claims delivery');
  assert.deepEqual(errors,[]);
  assert.deepEqual(failures,[]);
  record('No browser runtime errors or failed HTTP responses');
  await writeFile('inspection/verification.json',JSON.stringify({status:'passed',baseUrl,browser:'Chrome 155',checks,errors,failures},null,2));
  console.log(JSON.stringify({status:'passed',checks},null,2));
} catch(error) {
  await writeFile('inspection/verification.json',JSON.stringify({status:'failed',checks,error:error.stack},null,2));
  throw error;
} finally { await browser.close(); }
